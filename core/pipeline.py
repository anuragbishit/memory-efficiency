"""
Unified Orchestration Pipeline.
Integrates Subword Tokenization, Algorithmic Compression, and Intent Routing.
Represents Stages 1, 3, and 4 from the Minor Project Architecture.
"""

from typing import Dict, Any, Optional, List
from dataclasses import dataclass, asdict

from core.tokenization import (
    SubwordTokenizer,
    TokenAnalyzer,
    MultilingualFragmentationAnalyzer,
)
from core.compression import (
    NonAITokenCompressor,
    CompressionResult,
    CompressionLevel,
    InformationDensityAnalyzer,
)
from core.routing import (
    WeightedIntentRouter,
    IntentRouteDecision,
    CostLatencyOptimizer,
    RoutingStrategy,
)
from core.representation import PromptIRGenerator, PromptIR, IRFormat
from core.fidelity import ABFidelityTester, ABTestResult


@dataclass
class ProcessedPromptPayload:
    """End-to-end payload result generated by the pre-processing layer."""
    raw_prompt: str
    compressed_prompt: str
    encoding_used: str
    raw_tokens: int
    compressed_tokens: int
    tokens_saved: int
    token_reduction_pct: float
    routing_decision: Dict[str, Any]
    subword_comparison: Dict[str, Any]
    multilingual_fragmentation: Dict[str, Any]
    information_density_gain: Dict[str, Any]
    ast_code_summaries: List[Dict[str, Any]]
    rules_applied: List[str]
    prompt_ir: Dict[str, Any]
    ml_feature_vector: List[float]
    cost_latency_optimization: Dict[str, Any]
    total_pipeline_latency_ms: float
    ab_fidelity: Optional[Dict[str, Any]] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class LocalPreProcessingPipeline:
    """
    Consumer-side Local Pre-Processing Layer.
    Coordinates Tokenization, Non-AI Compression, Fragmentation Analysis,
    Information Density/Perplexity Evaluation, Intent Routing, and Prompt IR Generation.
    Dynamically optimizes model routing and calculates financial cost savings.
    """

    def __init__(
        self,
        default_encoding: str = "cl100k_base",
        compression_level: CompressionLevel = CompressionLevel.BALANCED,
        default_strategy: RoutingStrategy = RoutingStrategy.BALANCED,
    ):
        self.default_encoding = default_encoding
        self.compression_level = compression_level
        self.default_strategy = default_strategy

        self.tokenizer = SubwordTokenizer(default_encoding=default_encoding)
        self.analyzer = TokenAnalyzer(tokenizer=self.tokenizer)
        self.fragmentation_analyzer = MultilingualFragmentationAnalyzer(tokenizer=self.tokenizer)
        self.density_analyzer = InformationDensityAnalyzer(tokenizer=self.tokenizer)
        self.compressor = NonAITokenCompressor(tokenizer=self.tokenizer)
        self.cost_optimizer = CostLatencyOptimizer(default_strategy=default_strategy)
        self.router = WeightedIntentRouter(
            tokenizer=self.tokenizer,
            cost_optimizer=self.cost_optimizer,
            default_strategy=default_strategy
        )
        self.ir_generator = PromptIRGenerator(tokenizer=self.tokenizer)
        self.fidelity_tester = ABFidelityTester(
            tokenizer=self.tokenizer,
            compressor=self.compressor
        )

    def process(
        self,
        prompt: str,
        encoding_name: Optional[str] = None,
        compression_level: Optional[CompressionLevel] = None,
        run_ab_fidelity: bool = False,
        model_id: Optional[str] = None,
        api_key: Optional[str] = None,
    ) -> ProcessedPromptPayload:
        """
        Executes the end-to-end consumer pre-processing workflow:
          1. Subword tokenization analysis (cl100k_base vs o200k_base)
          2. Multilingual token fragmentation & script detection
          3. Intent recognition & complexity triage
          4. Algorithmic Non-AI token compression
          5. Information Density & Token Perplexity evaluation
          6. Aggregation of token savings & routing decisions
        """
        enc = encoding_name or self.default_encoding
        level = compression_level or self.compression_level

        # Stage 1: Intent Triage (Pillar 2)
        routing_decision: IntentRouteDecision = self.router.route(prompt, encoding_name=enc)

        # Stage 2: Tokenization & Multi-Encoding Comparison
        encoding_comparison = self.tokenizer.compare_encodings(prompt)

        # Stage 3: Multilingual Token Fragmentation Analysis
        fragmentation_metrics = self.fragmentation_analyzer.analyze(prompt)

        # Stage 4: Algorithmic Token Compression (Pillar 3)
        compression_result: CompressionResult = self.compressor.compress(
            prompt, level=level, encoding_name=enc
        )

        # Stage 5: Information Density & Perplexity Comparison
        density_comparison = self.density_analyzer.compare_compression_density_gain(
            raw_text=prompt,
            compressed_text=compression_result.compressed_text,
            encoding_name=enc,
        )

        # Stage 6: Prompt Intermediate Representation (IR) Generation (Topic 6)
        prompt_ir: PromptIR = self.ir_generator.generate_ir(
            compression_result.compressed_text,
            encoding_name=enc,
            format_type=IRFormat.TAGGED_KV
        )

        # Stage 7: Full Prompt Features & ML-Ready Feature Vector (Topic 7)
        extracted_features = self.router.feature_extractor.extract(prompt, compression_result.original_tokens)
        ml_vector = extracted_features.to_feature_vector()

        # Stage 8: Re-calculate Cost Optimization taking compressed tokens into account
        opt_report = self.cost_optimizer.optimize(
            complexity_score=routing_decision.complexity_score,
            prompt_tokens=compression_result.compressed_tokens,
            raw_prompt_tokens=compression_result.original_tokens,
            compute_budget_tokens=routing_decision.compute_budget_tokens,
            strategy=self.default_strategy,
            intent_category=routing_decision.ensemble_classification.get("consensus_intent"),
        )

        # Stage 9: Optional A/B Output Answer Fidelity Evaluation (Topic 10)
        fidelity_data = None
        if run_ab_fidelity:
            fidelity_res = self.fidelity_tester.run_ab_test(
                raw_prompt=prompt,
                compressed_prompt=compression_result.compressed_text,
                model_id=model_id or "cloud/gpt-4o-mini",
                api_key=api_key,
            )
            fidelity_data = fidelity_res.to_dict()

        total_latency = round(
            routing_decision.triage_latency_ms + compression_result.latency_ms, 3
        )

        return ProcessedPromptPayload(
            raw_prompt=prompt,
            compressed_prompt=compression_result.compressed_text,
            encoding_used=enc,
            raw_tokens=compression_result.original_tokens,
            compressed_tokens=compression_result.compressed_tokens,
            tokens_saved=compression_result.tokens_saved,
            token_reduction_pct=compression_result.compression_ratio_pct,
            routing_decision=routing_decision.to_dict(),
            subword_comparison=encoding_comparison,
            multilingual_fragmentation=asdict(fragmentation_metrics),
            information_density_gain=density_comparison,
            ast_code_summaries=compression_result.ast_code_summaries,
            rules_applied=compression_result.rules_applied,
            prompt_ir=prompt_ir.to_dict(),
            ml_feature_vector=ml_vector,
            cost_latency_optimization=opt_report.to_dict(),
            total_pipeline_latency_ms=total_latency,
            ab_fidelity=fidelity_data,
        )

    def run_fidelity_ab_test(
        self,
        prompt: str,
        compressed_prompt: Optional[str] = None,
        model_id: str = "cloud/gpt-4o-mini",
        api_key: Optional[str] = None,
        force_simulation: bool = False,
    ) -> ABTestResult:
        """Runs the end-to-end A/B Quality & Fidelity test on uncompressed vs compressed prompts."""
        return self.fidelity_tester.run_ab_test(
            raw_prompt=prompt,
            compressed_prompt=compressed_prompt,
            model_id=model_id,
            api_key=api_key,
            force_simulation=force_simulation,
        )
